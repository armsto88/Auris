#!/usr/bin/env python3
"""Phase 4a: generate the EasyEDA script that adds the keep-outs and the copper planes.

    python3 hardware/layout/phase4_planes.py <export .epro2>

Writes hardware/easyeda/pcb-phase4-planes.js. What it adds (mm, board frame):
- copper keep-outs (no wires, fills, pours, inner planes) of diameter 7.2 mm around MH1-MH4;
- under U301's body: no pours/fills on L1 (Quectel: nothing but the module on top) and no wires on
  L2 (HD V1.0 p.17: uninterrupted reference ground directly below the module);
- a 2.4 mm cut in the L2 ground under J302's signal pad (HD V1.0 section 5.2);
- GND pours: L2 (Inner1) over the whole board, L1 and L4 at the lowest priority;
- L3 (Inner2) power pours: 3V3 over the MCU/3.3 V corner, VMODEM from U207's output up to R301.
Pours are rebuilt at the end. The document is not saved (pcb-export.js does that).
"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, os.path.join(ROOT, "hardware", "tools")); sys.path.insert(0, HERE)
from pcb_board import load_board  # noqa: E402
import place  # noqa: E402

MIL = 1 / 0.0254
LAYER = {"L1": 1, "L2": 15, "L3": 16, "L4": 2, "MULTI": 12}
NO_WIRES, NO_FILLS, NO_POURS, NO_INNER = 5, 6, 7, 8


def mil(v):
    return round(v * MIL, 2)


def pts(points):
    """Closed polygon source for pcb_MathPolygon.createPolygon: [x0, y0, "L", x1, y1, ...] in mil."""
    out = [mil(points[0][0]), mil(points[0][1]), "L"]
    for x, y in points[1:]:
        out += [mil(x), mil(y)]
    return out


def rect(x0, y0, x1, y1):
    """Rectangle source ["R", left, top, w, h, 0, 0]: EasyEDA takes the top-left corner in board
    coordinates (phase 1 finding). Region/Pour.create rejected point-list sources (2026-11-20)."""
    return ["R", mil(x0), mil(y1), mil(x1 - x0), mil(y1 - y0), 0, 0]


def main():
    board = load_board(sys.argv[1], ROOT)
    P = board.parts
    W, H = place.W, place.H
    nx0, ny0, nx1, ny1 = place.NOTCH
    board_poly = rect(0, 0, W, H)   # full rectangle; EasyEDA clips pours to the board outline (notch checked after the run)
    u = P["U301"]; ux0, uy0, ux1, uy1 = u.extent(0, u.x, u.y, u.angle)
    j = P["J302"]; sig = next(q for q in j.fp.pads if P["J302"].nets.get(q.num) == "ANT_FEED")
    jx, jy = j.pad_xy(sig, j.x, j.y, j.angle)
    regions = []   # (name, layer, polygon source, rules)
    for i, (hx, hy) in enumerate(place.HOLES, 1):
        regions.append((f"MH keep-out {i}", LAYER["MULTI"], ["CIRCLE", mil(hx), mil(hy), mil(3.6)], [NO_WIRES, NO_FILLS, NO_POURS, NO_INNER]))
    regions.append(("U301 no top copper", LAYER["L1"], rect(ux0, uy0, ux1, uy1), [NO_FILLS, NO_POURS]))
    regions.append(("U301 solid ground below", LAYER["L2"], rect(ux0, uy0, ux1, uy1), [NO_WIRES]))
    regions.append(("J302 ground cut", LAYER["L2"], ["CIRCLE", mil(jx), mil(jy), mil(1.2)], [NO_FILLS, NO_POURS, NO_INNER]))
    pours = []     # (name, net, layer, polygon source, priority)
    pours.append(("GND L2", "GND", LAYER["L2"], board_poly, 1))
    pours.append(("GND L1", "GND", LAYER["L1"], board_poly, 9))
    pours.append(("GND L4", "GND", LAYER["L4"], board_poly, 9))
    # L3: 3V3 over the MCU / 3.3 V corner; VMODEM from U207's output up to R301 (under U301, over solid L2)
    pours.append(("3V3 L3", "3V3", LAYER["L3"], rect(1.0, 57.0, 44.0, H - 0.5), 3))
    pours.append(("VMODEM L3 a", "VMODEM", LAYER["L3"], rect(44.5, 53.5, 63.5, 71.0), 3))      # U207 output area
    pours.append(("VMODEM L3 b", "VMODEM", LAYER["L3"], rect(50.5, 70.5, 61.5, 102.0), 3))     # strip up to R301, under U301 over the solid L2
    js = TEMPLATE.replace("__REGIONS__", json_rows(regions)).replace("__POURS__", json_rows(pours))
    out = os.path.join(ROOT, "hardware", "easyeda", "pcb-phase4-planes.js")
    open(out, "w").write(js)
    print(f"wrote {out}: {len(regions)} regions, {len(pours)} pours; U301 body {ux0:.2f}-{ux1:.2f} x {uy0:.2f}-{uy1:.2f}, J302 signal pad ({jx:.2f}, {jy:.2f})")


def json_rows(rows):
    import json
    return "[\n" + ",\n".join("    " + json.dumps(r) for r in rows) + "\n  ]"


TEMPLATE = r"""// Auris rev A layout, phase 4a: keep-outs and copper planes (generated by
// hardware/layout/phase4_planes.py; do not edit by hand). Coordinates in mil, board origin bottom-left.
// Region rules: 5 no wires, 6 no fills, 7 no pours, 8 no inner electrical layers. Layers: 1 top,
// 15 Inner1 (L2 GND), 16 Inner2 (L3 power), 2 bottom, 12 multi-layer.
// The document is NOT saved. Run: __aurisStart("pcb-phase4-planes.js", { titleRe: /^Auris phase 4a/ })
(async () => {
  const PCB_UUID = "1171ec2ee0a2c106";
  const REGIONS = __REGIONS__;
  const POURS = __POURS__;
  const out = [];
  const msg = (e) => String((e && e.message) || e).slice(0, 80);
  await eda.dmt_EditorControl.openDocument(PCB_UUID);
  await new Promise((r) => setTimeout(r, 1500));
  // idempotent: remove regions and pours this script made earlier (by name)
  const names = new Set([...REGIONS.map((r) => r[0]), ...POURS.map((p) => p[0])].map((n) => n.toUpperCase()));
  const mine = (n) => { n = String(n || "").toUpperCase(); return names.has(n) || names.has(n.replace(/\d+$/, "")); };   // EasyEDA upper-cases names and suffixes duplicates
  try {
    const oldR = (await eda.pcb_PrimitiveRegion.getAll()).filter((r) => mine(r.getState_RegionName && r.getState_RegionName()));
    if (oldR.length) out.push(`removed ${oldR.length} earlier regions: ${await eda.pcb_PrimitiveRegion.delete(oldR.map((r) => r.getState_PrimitiveId()))}`);
    const oldP = (await eda.pcb_PrimitivePour.getAll()).filter((p) => mine(p.getState_PourName && p.getState_PourName()));
    if (oldP.length) out.push(`removed ${oldP.length} earlier pours: ${await eda.pcb_PrimitivePour.delete(oldP.map((p) => p.getState_PrimitiveId()))}`);
  } catch (e) { out.push("cleanup: " + msg(e)); }
  let group = null;
  try { group = await eda.pcb_Document.beginCommandGroup("Auris phase 4a planes"); } catch (_) { group = null; }
  let nr = 0, np = 0;
  for (const [name, layer, src, rules] of REGIONS) {
    try {
      const poly = eda.pcb_MathPolygon.createPolygon(src);
      if (!poly) { out.push(`${name}: polygon undefined`); continue; }
      const r = await eda.pcb_PrimitiveRegion.create(layer, poly, rules, name, 4, false);
      if (r) nr++; else out.push(`${name}: create returned ${r}`);
    } catch (e) { out.push(`${name}: ${msg(e)}`); }
  }
  for (const [name, net, layer, src, prio] of POURS) {
    try {
      const poly = eda.pcb_MathPolygon.createPolygon(src);
      if (!poly) { out.push(`${name}: polygon undefined`); continue; }
      const p = await eda.pcb_PrimitivePour.create(net, layer, poly, "solid", false, name, prio, 4, false);
      if (p) np++; else out.push(`${name}: create returned ${p}`);
    } catch (e) { out.push(`${name}: ${msg(e)}`); }
  }
  let rebuilt = "?";
  try { const l = await eda.pcb_PrimitivePour.rebuildAllCopperRegions(); rebuilt = Array.isArray(l) ? l.length : String(l); } catch (e) { rebuilt = "ERR " + msg(e); }
  if (group && group.groupId) { try { await eda.pcb_Document.commitCommandGroup(group.groupId); } catch (_) { /* ignore */ } }
  out.unshift(`regions ${nr} of ${REGIONS.length}; pours ${np} of ${POURS.length}; poured areas after rebuild: ${rebuilt}`);
  eda.sys_Dialog.showInformationMessage(out.join("\n"), "Auris phase 4a");
})().catch((e) => eda.sys_Dialog.showInformationMessage("Auris phase 4a stopped: " + ((e && e.stack) || e), "Auris phase 4a"));
"""

if __name__ == "__main__":
    main()
