#!/usr/bin/env python3
"""Apply a list of part moves to an exported placement and write the next pass.

    python3 hardware/layout/apply_moves.py <base export .epro2> <moves.csv> <tag>

moves.csv columns: designator, x_mm, y_mm, angle (board frame, mm, counter-clockwise degrees).
Every other part keeps its exported position. Writes hardware/layout/placement-<tag>.csv and
.png, and hardware/easyeda/pcb-phase3-place-<tag>.js (moves only the listed parts), then runs
place.py's checks and prints the note-target distances of the moved parts. Used for pass 4
(2026-11-20), whose moves come from hardware/review/2026-11-19-placement-review.md.
"""
import csv, math, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, os.path.join(ROOT, "hardware", "tools"))
sys.path.insert(0, HERE)
from pcb_board import load_board  # noqa: E402
import place  # noqa: E402


def main():
    src, moves_path, tag = sys.argv[1:4]
    board = load_board(src, ROOT)
    pl = {d: (p.x, p.y, p.angle) for d, p in board.parts.items()}
    moves = list(csv.DictReader(open(moves_path)))
    for r in moves:
        d = r["designator"]
        if d not in pl:
            sys.exit(f"{d}: not on the board")
        pl[d] = (float(r["x_mm"]), float(r["y_mm"]), int(float(r["angle"])))
    targets = place.note_targets(board)
    lines, far = place.check(board, pl, targets)
    print("\n".join(lines))
    moved = {r["designator"] for r in moves}
    print("note targets of the moved parts:")
    for dd, d, ref in sorted(far, key=lambda t: t[1]):
        if d in moved:
            print(f"  {d} -> {ref}: {dd:.1f} mm")
    place.write_csv(board, pl, os.path.join(HERE, f"placement-{tag}.csv"))
    place.render(board, pl, os.path.join(HERE, f"placement-{tag}.png"), f"Auris rev A placement {tag} (top view, mm)")
    sub = {d: pl[d] for d in moved}
    js_path = os.path.join(ROOT, "hardware", "easyeda", f"pcb-phase3-place-{tag}.js")
    place.TEMPLATE_SAVED = place.TEMPLATE
    place.write_js(board, sub, js_path, tag)
    txt = open(js_path).read().replace(
        "move every part to its planned place (generated by\n// hardware/layout/place.py,",
        f"move the parts listed in placement-{tag}-moves.csv (generated by\n// hardware/layout/apply_moves.py,")
    txt = txt.replace('__aurisStart("pcb-phase3-place.js"', f'__aurisStart("pcb-phase3-place-{tag}.js"')
    open(js_path, "w").write(txt)
    print(f"moved {len(moved)} parts; wrote placement-{tag}.csv/.png and hardware/easyeda/pcb-phase3-place-{tag}.js")


if __name__ == "__main__":
    main()
